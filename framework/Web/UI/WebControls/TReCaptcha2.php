/**
 * TReCaptcha2 class.
 *
 * TReCaptcha2 displays a reCAPTCHA (a token displayed as an image) that can be used
 * to determine if the input is entered by a real user instead of some program. It can
 * also prevent multiple submits of the same form either by accident, or on purpose (ie. spamming).
 *
 * The reCAPTCHA to solve (a string consisting of two separate words) displayed is automatically
 * generated by the reCAPTCHA system at recaptcha.net. However, in order to use the services
 * of the site you will need to register and get a public and a private API key pair, and
 * supply those to the reCAPTCHA control through setting the {@see setSecretKey SecretKey}
 * and {@see setSiteKey SiteKey} properties.
 *
 * Currently the reCAPTCHA API supports only one reCAPTCHA field per page, so you MUST make sure that all
 * your input is protected and validated by a single reCAPTCHA control. Placing more than one reCAPTCHA
 * control on the page will lead to unpredictable results, and the user will most likely unable to solve
 * any of them successfully.
 *
 * Upon postback, user input can be validated by calling {@see validate()}, which posts the
 * response token and {@see setSecretKey SecretKey} to Google's siteverify endpoint
 * ({@see VERIFY_URL}). Validation therefore needs the SecretKey and outbound HTTPS access.
 * The {@see \Prado\Web\UI\WebControls\TReCaptcha2Validator} control can also be used to do validation, which provides
 * server-side validation. Calling (@link validate()) will invalidate the token supplied, so all consecutive
 * calls to the method - without solving a new captcha - will return false. Therefore if implementing a multi-stage
 * input process, you must make sure that you call validate() only once, either at the end of the input process, or
 * you store the result till the end of the processing.
 *
 * The following template shows a typical use of TReCaptcha control:
 * ```php
 * <com:TReCaptcha2 ID="Captcha"
 *                 SiteKey="..."
 *                 SecretKey="..."
 * />
 * <com:TReCaptcha2Validator ControlToValidate="Captcha"
 *                          ErrorMessage="You are challenged!" />
 * ```
 *
 * @author Cristian Camilo Naranjo Valencia
 * @since 3.3.1
 * @method TActiveControlAdapter getAdapter()
 */
class TReCaptcha2 extends TActivePanel implements \Prado\Web\UI\ActiveControls\ICallbackEventHandler, \Prado\Web\UI\IValidatable
{
	public const ChallengeFieldName = 'g-recaptcha-response';
	/**
	 * Google's endpoint that verifies a response token.
	 * @since 4.3.3
	 */
	public const VERIFY_URL = 'https://www.google.com/recaptcha/api/siteverify';
	private $_isValid = true;
	/** @var ?bool the siteverify result of this request, null before verification. */
	private $_verified;
	/** @var ?array Google's decoded siteverify answer of this request. */
	private $_verifyResult;

	/**
	 * Creates a new callback control, sets the adapter to
	 * TActiveControlAdapter. If you override this class, be sure to set the
	 * adapter appropriately by, for example, by calling this constructor.
	 */
	public function __construct()
	{
		parent::__construct();
		$this->setAdapter(new TActiveControlAdapter($this));
	}

	/**
	 * @return \Prado\Web\UI\ActiveControls\TBaseActiveCallbackControl standard callback control options.
	 */
	public function getActiveControl()
	{
		return $this->getAdapter()->getBaseActiveControl();
	}

	/**
	 * @return \Prado\Web\UI\ActiveControls\TCallbackClientSide client side request options.
	 */
	public function getClientSide()
	{
		return $this->getActiveControl()->getClientSide();
	}

	public function getClientClassName()
	{
		return 'Prado.WebUI.TReCaptcha2';
	}

	public function getTagName()
	{
		return 'div';
	}

	/**
	 * Returns true if this control validated successfully.
	 * Defaults to true.
	 * @return bool wether this control validated successfully.
	 */
	public function getIsValid()
	{
		return $this->_isValid;
	}

	/**
	 * @param bool $value wether this control is valid.
	 */
	public function setIsValid($value)
	{
		$this->_isValid = TPropertyValue::ensureBoolean($value);
	}

	public function getValidationPropertyValue()
	{
		return $this->getRequest()->itemAt($this->getResponseFieldName());
	}

	public function getResponseFieldName()
	{
		$captchas = $this->getPage()->findControlsByType(TReCaptcha2::class, false);
		$cont = 0;
		$responseFieldName = self::ChallengeFieldName;
		foreach ($captchas as $captcha) {
			if ($this->getClientID() == $captcha->getClientID()) {
				$responseFieldName .= ($cont > 0) ? '-' . $cont : '';
			}
			$cont++;
		}
		return $responseFieldName;
	}

	/**
	 * Returns your site key.
	 * @return string site key
	 */
	public function getSiteKey()
	{
		return $this->getViewState('SiteKey');
	}

	/**
	 * @param string $value your site key.
	 */
	public function setSiteKey($value)
	{
		$this->setViewState('SiteKey', TPropertyValue::ensureString($value));
	}

	/**
	 * Returns your secret key.
	 * @return string secret key
	 */
	public function getSecretKey()
	{
		return $this->getViewState('SecretKey');
	}

	/**
	 * @param string $value your secret key.
	 */
	public function setSecretKey($value)
	{
		$this->setViewState('SecretKey', TPropertyValue::ensureString($value));
	}

	/**
	 * Returns your language.
	 * @return string language
	 */
	public function getLanguage()
	{
		return $this->getViewState('Language', 'en');
	}

	/**
	 * @param string $value your language.
	 */
	public function setLanguage($value)
	{
		$this->setViewState('Language', TPropertyValue::ensureString($value), 'en');
	}

	/**
	 * Returns the color theme of the widget.
	 * @return string theme name
	 */
	public function getTheme()
	{
		return $this->getViewState('Theme', 'light');
	}

	/**
	 * The color theme of the widget.
	 * Default: light
	 * @param string $value the color theme of the widget.
	 */
	public function setTheme($value)
	{
		$this->setViewState('Theme', TPropertyValue::ensureString($value), 'light');
	}

	/**
	 * Returns the type of CAPTCHA to serve.
	 * @return string captcha type
	 */
	public function getType()
	{
		return $this->getViewState('Type', 'image');
	}

	/**
	 * The type of CAPTCHA to serve.
	 * Default: image
	 * @param string $value the type of CAPTCHA to serve.
	 */
	public function setType($value)
	{
		$this->setViewState('Type', TPropertyValue::ensureString($value), 'image');
	}

	/**
	 * Returns the size of the widget.
	 * @return string widget size
	 */
	public function getSize()
	{
		return $this->getViewState('Size', 'normal');
	}

	/**
	 * The size of the widget.
	 * Default: normal
	 * @param string $value the size of the widget.
	 */
	public function setSize($value)
	{
		$this->setViewState('Size', TPropertyValue::ensureString($value), 'normal');
	}

	/**
	 * Returns the tabindex of the widget and challenge.
	 * If other elements in your page use tabindex, it should be set to make user navigation easier.
	 * @return string tab index
	 */
	public function getTabIndex()
	{
		return $this->getViewState('TabIndex', 0);
	}

	/**
	 * The tabindex of the widget and challenge.
	 * If other elements in your page use tabindex, it should be set to make user navigation easier.
	 * Default: 0
	 * @param string $value the tabindex of the widget and challenge.
	 */
	public function setTabIndex($value)
	{
		$this->setViewState('TabIndex', TPropertyValue::ensureInteger($value), 0);
	}

	/**
	 * Resets the reCAPTCHA widget.
	 * Optional widget ID, defaults to the first widget created if unspecified.
	 */
	public function reset()
	{
		$this->getPage()->getCallbackClient()->callClientFunction('grecaptcha.reset', [[$this->getWidgetId()]]);
	}

	/**
	 * Returns the reCAPTCHA verification token set by the widget.
	 *
	 * @return string The captcha response token, or an empty string when not yet set.
	 * @since 4.3.3
	 */
	public function getCaptchaResponse()
	{
		return $this->getViewState('CaptchaResponse', '');
	}

	/**
	 * Sets the reCAPTCHA verification token.
	 * @param string $value The captcha response token.
	 * @since 4.3.3
	 */
	public function setCaptchaResponse($value)
	{
		$this->setViewState('CaptchaResponse', TPropertyValue::ensureString($value), '');
	}

	/**
	 * Returns the reCAPTCHA verification token, as {@see getCaptchaResponse()} does.
	 * This method shadows {@see \Prado\TApplicationComponent::getResponse()}; use
	 * `getApplication()->getResponse()` for the HTTP response.
	 * @return string The captcha response token, or an empty string when not yet set.
	 * @deprecated 4.3.3 Use {@see getCaptchaResponse()}. Removed in 4.4.0, where
	 *   getResponse() returns the HTTP response.
	 */
	public function getResponse()
	{
		return $this->getCaptchaResponse();
	}

	/**
	 * Sets the reCAPTCHA verification token, as {@see setCaptchaResponse()} does.
	 * @param string $value The captcha response token.
	 * @deprecated 4.3.3 Use {@see setCaptchaResponse()}. Removed in 4.4.0.
	 */
	public function setResponse($value)
	{
		$this->setCaptchaResponse($value);
	}

	public function getWidgetId()
	{
		return $this->getViewState('WidgetId', 0);
	}

	public function setWidgetId($value)
	{
		$this->setViewState('WidgetId', TPropertyValue::ensureInteger($value), 0);
	}

	protected function getClientOptions()
	{
		$options['ID'] = $this->getClientID();
		$options['EventTarget'] = $this->getUniqueID();
		$options['FormID'] = $this->getPage()->getForm()->getClientID();
		$options['onCallback'] = $this->hasEventHandler('OnCallback');
		$options['onCallbackExpired'] = $this->hasEventHandler('OnCallbackExpired');
		$options['options']['sitekey'] = $this->getSiteKey();
		if ($theme = $this->getTheme()) {
			$options['options']['theme'] = $theme;
		}
		if ($type = $this->getType()) {
			$options['options']['type'] = $type;
		}
		if ($size = $this->getSize()) {
			$options['options']['size'] = $size;
		}
		if ($tabIndex = $this->getTabIndex()) {
			$options['options']['tabindex'] = $tabIndex;
		}

		return $options;
	}

	protected function registerClientScript()
	{
		$id = $this->getClientID();
		$options = TJavaScript::encode($this->getClientOptions());
		$className = $this->getClientClassName();
		$cs = $this->getPage()->getClientScript();
		$code = "new $className($options);";

		$cs->registerPradoScript('ajax');
		$cs->registerEndScript("grecaptcha:$id", $code);
	}

	/**
	 * Verifies the posted response token with Google's siteverify endpoint.
	 * Repeated calls in the same request return the first result.
	 * @return bool whether Google accepted the token.
	 */
	public function validate()
	{
		if ($this->_verified === null) {
			$this->_verified = $this->verifyResponse((string) $this->getValidationPropertyValue());
		}
		return $this->_verified;
	}

	/**
	 * @return ?array Google's decoded siteverify answer from this request, or null before verification or on failure.
	 * @since 4.3.3
	 */
	public function getVerifyResult(): ?array
	{
		return $this->_verifyResult;
	}

	/**
	 * Posts a response token to siteverify. An empty token or SecretKey fails without a request.
	 * A transport failure logs a warning and fails.
	 * @param string $response the response token from the widget.
	 * @return bool whether Google answered `"success": true`.
	 * @since 4.3.3
	 */
	protected function verifyResponse(string $response): bool
	{
		if ($response === '' || ($secret = (string) $this->getSecretKey()) === '') {
			return false;
		}
		$fields = ['secret' => $secret, 'response' => $response];
		if (($address = (string) $this->getRequest()->getUserHostAddress()) !== '') {
			$fields['remoteip'] = $address;
		}
		$answer = $this->postVerifyRequest(self::VERIFY_URL, http_build_query($fields));
		if ($answer === null) {
			Prado::warning('TReCaptcha2 could not reach siteverify.', static::class);
			return false;
		}
		$data = json_decode($answer, true);
		$this->_verifyResult = is_array($data) ? $data : null;
		return ($this->_verifyResult['success'] ?? false) === true;
	}

	/**
	 * Posts a form-encoded body and returns the response body.  cURL is used when it is
	 * loaded, otherwise an HTTP stream context.
	 * @param string $url the URL to post to.
	 * @param string $body the `application/x-www-form-urlencoded` body.
	 * @return ?string the response body, or null when the request fails or the status is not 2xx.
	 * @since 4.3.3
	 */
	protected function postVerifyRequest(string $url, string $body): ?string
	{
		if (function_exists('curl_init')) {
			$ch = curl_init($url);
			curl_setopt_array($ch, [
				CURLOPT_POST => true,
				CURLOPT_POSTFIELDS => $body,
				CURLOPT_RETURNTRANSFER => true,
				CURLOPT_HTTPHEADER => ['Content-Type: application/x-www-form-urlencoded'],
				CURLOPT_TIMEOUT => 10,
			]);
			$result = curl_exec($ch);
			$status = (int) curl_getinfo($ch, CURLINFO_RESPONSE_CODE);
			return (is_string($result) && $status >= 200 && $status < 300) ? $result : null;
		}
		$context = stream_context_create(['http' => [
			'method' => 'POST',
			'header' => "Content-Type: application/x-www-form-urlencoded\r\n",
			'content' => $body,
			'timeout' => 10,
			'ignore_errors' => false,
		]]);
		$result = @file_get_contents($url, false, $context);
		return is_string($result) ? $result : null;
	}

	/**
	 * Checks for API keys
	 * @param mixed $param event parameter
	 */
	public function onPreRender($param)
	{
		parent::onPreRender($param);

		if ("" == $this->getSiteKey()) {
			throw new TConfigurationException('recaptcha_publickey_unknown');
		}
		if ("" == $this->getSecretKey()) {
			throw new TConfigurationException('recaptcha_privatekey_unknown');
		}

		// need to register captcha fields so they will be sent postback
		$this->getPage()->registerRequiresPostData($this->getResponseFieldName());
		$this->getPage()->getClientScript()->registerHeadScriptFile('grecaptcha2', 'https://www.google.com/recaptcha/api.js?onload=TReCaptcha2_onloadCallback&render=explicit&hl=' . $this->getLanguage());
	}

	protected function addAttributesToRender($writer)
	{
		$writer->addAttribute('id', $this->getClientID());
		parent::addAttributesToRender($writer);
	}

	public function raiseCallbackEvent($param)
	{
		$params = $param->getCallbackParameter();
		if ($params instanceof \stdClass) {
			$callback = property_exists($params, 'onCallback');
			$callbackExpired = property_exists($params, 'onCallbackExpired');

			if ($callback) {
				$this->setWidgetId($params->widgetId);
				$this->setCaptchaResponse($params->response);
				$this->getPage()->getCallbackClient()->jQuery($params->responseField, 'text', [$params->response]);

				if ($params->onCallback) {
					$this->onCallback($param);
				}
			}

			if ($callbackExpired) {
				$this->setCaptchaResponse('');
				$this->reset();

				if ($params->onCallbackExpired) {
					$this->onCallbackExpired($param);
				}
			}
		}
	}

	public function onCallback($param)
	{
		$this->raiseEvent('OnCallback', $this, $param);
	}

	public function onCallbackExpired($param)
	{
		$this->raiseEvent('OnCallbackExpired', $this, $param);
	}

	public function render($writer)
	{
		$this->registerClientScript();
		parent::render($writer);
	}
}
