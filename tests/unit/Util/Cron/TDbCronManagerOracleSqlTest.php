/**
 * Command of {@see TDbCronManagerOracleSqlConnection}: a query returns the scripted rows, and a
 * query of a missing table or column throws.
 */
class TDbCronManagerOracleSqlCommand extends TTestLockCommand
{
	public function __construct(string $sql, public array $rows = [], mixed $scalar = null, public bool $fails = false)
	{
		parent::__construct($sql, $scalar, null, 1);
	}

	public function query()
	{
		$this->runs++;
		if ($this->fails) {
			throw new \Exception('ORA-00904: invalid identifier');
		}
		$rows = $this->rows;
		return new class ($rows) {
			public function __construct(private array $rows)
			{
			}

			public function readAll()
			{
				return $this->rows;
			}

			public function close()
			{
			}
		};
	}

	public function queryRow($fetchAssociative = true)
	{
		$this->runs++;
		return $this->rows[0] ?? false;
	}
}

/**
 * Oracle connection that records the SQL of each command.  {@see $answers} scripts the result of
 * a command by a fragment of its SQL: an array of rows, or a scalar.  A command whose SQL holds a
 * fragment of {@see $missing} fails its query, as for a missing table or column.
 */
class TDbCronManagerOracleSqlConnection extends TTestLockConnection
{
	/** @var array<string, mixed> the results by SQL fragment. */
	public array $answers = [];

	/** @var string[] the SQL fragments of failing queries. */
	public array $missing = [];

	public function __construct()
	{
		parent::__construct(TDbDriver::DRIVER_OCI);
	}

	public function createCommand($query)
	{
		$answer = null;
		foreach ($this->answers as $fragment => $value) {
			if (str_contains($query, $fragment)) {
				$answer = $value;
				break;
			}
		}
		$fails = false;
		foreach ($this->missing as $fragment) {
			$fails = $fails || str_contains($query, $fragment);
		}
		return $this->commands[] = new TDbCronManagerOracleSqlCommand($query, is_array($answer) ? $answer : [], is_array($answer) ? null : $answer, $fails);
	}

	/**
	 * @return string[] the SQL of the commands, in order.
	 */
	public function sql(): array
	{
		return array_map(fn ($cmd) => preg_replace('/\s+/', ' ', $cmd->sql), $this->commands);
	}
}

/**
 * TDbCronManager on a {@see TDbCronManagerOracleSqlConnection}.
 */
class TDbCronManagerOracleSqlManager extends TDbCronManager
{
	public ?TDbCronManagerOracleSqlConnection $recorder = null;

	public function getDbConnection(): IDataConnection
	{
		return $this->recorder;
	}
}

/**
 * The SQL that TDbCronManager runs on Oracle: the table, its indexes, its migration, paging, the
 * inserted row's id, and the rows it reads.
 */
class TDbCronManagerOracleSqlTest extends \PHPUnit\Framework\TestCase
{
	private ?TDbCronManagerOracleSqlManager $_manager = null;

	protected function tearDown(): void
	{
		$this->_manager?->unlisten();
		$this->_manager = null;
	}

	private function newManager(): TDbCronManagerOracleSqlManager
	{
		$this->_manager = new TDbCronManagerOracleSqlManager();
		$this->_manager->recorder = new TDbCronManagerOracleSqlConnection();
		return $this->_manager;
	}

	private function newTask(string $name): TTestCronModuleTask
	{
		$task = new TTestCronModuleTask();
		$task->setName($name);
		$task->setSchedule('0 0 1 1 ? 2099');
		$task->setPropertyA("a \0 NUL");
		return $task;
	}

	/**
	 * @return resource a stream of the value, as pdo_oci fetches a `CLOB`
	 */
	private function clob(string $value)
	{
		$stream = fopen('php://memory', 'r+');
		fwrite($stream, $value);
		rewind($stream);
		return $stream;
	}

	public function testCreatesTheTableWithOracleTypes()
	{
		$manager = $this->newManager();
		$manager->recorder->missing = ['SELECT * FROM crontabs WHERE 0=1'];

		self::assertSame(['created' => true, 'column' => null, 'run' => false], $manager->migrateTable());

		$sql = $manager->recorder->sql();
		$create = $sql[1];
		self::assertStringStartsWith('CREATE TABLE crontabs (tabuid NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ', $create);
		foreach (TDbCronManager::ORACLE_COLUMNS as $column => $definition) {
			self::assertStringContainsString($column . ' ' . $definition, $create);
		}
		self::assertStringContainsString('nextexectime NUMBER(19) NULL', $create, 'a trigger after 2038 fits');
		self::assertStringContainsString('processcount NUMBER(10) DEFAULT 0 NOT NULL', $create, 'DEFAULT precedes the constraint');
		self::assertStringContainsString('options CLOB NULL', $create);
		self::assertStringContainsString('active NUMBER(1) NULL', $create);
		foreach (['IF NOT EXISTS', 'BIGINT', 'MEDIUMTEXT', 'BOOLEAN', 'VARCHAR ', 'VARCHAR(', 'DEFAULT NULL', '`'] as $absent) {
			self::assertStringNotContainsString($absent, $create);
		}
		self::assertSame([
			'CREATE INDEX crontabs_tname ON crontabs (name)',
			'CREATE INDEX crontabs_tclass ON crontabs (task)',
			'CREATE INDEX crontabs_tnext ON crontabs (nextexectime)',
			'CREATE INDEX crontabs_tuser ON crontabs (username)',
			'CREATE INDEX crontabs_tactive ON crontabs (active)',
		], array_slice($sql, 2, 5));
	}

	public function testMigratesAnOldTableWithOracleSyntax()
	{
		$manager = $this->newManager();
		$columns = array_merge(['nextexectime'], array_keys(TDbCronManager::RUN_COLUMNS));
		$manager->recorder->missing = array_map(fn ($column) => 'SELECT ' . $column . ' FROM', $columns);
		$task = $this->newTask('oldtask');
		$manager->recorder->answers = ['SELECT name, options, lastexectime FROM' => [
			['NAME' => 'oldtask', 'OPTIONS' => $this->clob(base64_encode(serialize($task))), 'LASTEXECTIME' => null],
		]];

		self::assertSame(['created' => false, 'column' => 1, 'run' => true], $manager->migrateTable());

		$sql = $manager->recorder->sql();
		self::assertContains('ALTER TABLE crontabs ADD (nextexectime NUMBER(19) NULL)', $sql);
		self::assertContains('CREATE INDEX crontabs_tnext ON crontabs(nextexectime)', $sql);
		foreach (array_keys(TDbCronManager::RUN_COLUMNS) as $column) {
			self::assertContains('ALTER TABLE crontabs ADD (' . $column . ' ' . TDbCronManager::ORACLE_COLUMNS[$column] . ')', $sql);
		}
		self::assertStringNotContainsString('ADD COLUMN', implode("\n", $sql));
		$update = array_values(array_filter($manager->recorder->commands, fn ($cmd) => str_starts_with($cmd->sql, 'UPDATE crontabs SET nextexectime')));
		self::assertCount(1, $update);
		self::assertSame('oldtask', $update[0]->bound[':name'], 'the upper case row is read');
		self::assertGreaterThan(2 ** 31, $update[0]->bound[':ntime'], 'the CLOB stream is read and decoded');
	}

	public function testOtherDriversKeepTheirMigrationSql()
	{
		$manager = $this->newManager();
		$manager->recorder->driver = TDbDriver::DRIVER_MYSQL;
		self::assertSame('ALTER TABLE crontabs ADD COLUMN paused INT NULL DEFAULT NULL', PradoUnit::invoke($manager, 'getAddColumnSql', 'paused', 'INT'));
		self::assertSame(' LIMIT 2 OFFSET 4', PradoUnit::invoke($manager, 'limitClause', 2, 4));
	}

	public function testPagesWithOffsetFetch()
	{
		$manager = $this->newManager();
		self::assertSame('', PradoUnit::invoke($manager, 'limitClause', 0, 5));
		self::assertSame(' FETCH NEXT 3 ROWS ONLY', PradoUnit::invoke($manager, 'limitClause', 3, 0));
		self::assertSame(' OFFSET 4 ROWS FETCH NEXT 2 ROWS ONLY', PradoUnit::invoke($manager, 'limitClause', 2, 4));

		$task = $this->newTask('logged');
		$manager->recorder->answers = ['SELECT * FROM crontabs WHERE active IS NULL' => [
			['TABUID' => '7', 'NAME' => 'logged', 'OPTIONS' => $this->clob(base64_encode(serialize($task))), 'LASTRESULT' => 'ok'],
		]];
		$log = $manager->getCronLog(null, 2, 4, true);
		self::assertStringEndsWith(' ORDER BY lastExecTime DESC, tabuid DESC, processCount DESC OFFSET 4 ROWS FETCH NEXT 2 ROWS ONLY', end($manager->recorder->commands)->sql);
		self::assertSame('7', $log[0]['tabuid'], 'the columns are lower case');
		self::assertSame(serialize($task), $log[0]['options'], 'the CLOB is read and decoded');
	}

	public function testGetTaskFetchesOneUpperCaseRow()
	{
		$manager = $this->newManager();
		$task = $this->newTask('readback');
		$manager->recorder->answers = ['SELECT * FROM crontabs WHERE name=:name' => [
			['NAME' => 'readback', 'OPTIONS' => $this->clob(base64_encode(serialize($task))), 'NEXTEXECTIME' => '4070908800'],
		]];
		$read = $manager->getTask('readback', false);
		self::assertSame('SELECT * FROM crontabs WHERE name=:name AND active IS NOT NULL FETCH NEXT 1 ROWS ONLY', end($manager->recorder->commands)->sql);
		self::assertInstanceOf(TTestCronModuleTask::class, $read);
		self::assertSame("a \0 NUL", $read->getPropertyA());
	}

	public function testTaskExistsAggregatesTheUserName()
	{
		$manager = $this->newManager();
		$manager->recorder->answers = ['SELECT COUNT(*) AS count' => [['COUNT' => '1', 'USERNAME' => 'admin']]];
		self::assertTrue($manager->taskExists('named'));
		self::assertSame('SELECT COUNT(*) AS count, MAX(username) AS username FROM crontabs WHERE name=:name AND active IS NOT NULL', end($manager->recorder->commands)->sql);
	}

	public function testTaskOptionsAreBase64OnOracle()
	{
		$manager = $this->newManager();
		$task = $this->newTask('encoded');
		$options = PradoUnit::invoke($manager, 'serializeTask', $task);
		self::assertStringNotContainsString("\0", $options);
		self::assertSame(serialize($task), PradoUnit::invoke($manager, 'decodeTaskOptions', $options));
	}

	public function testInsertIdIsTheIdentitySequenceValue()
	{
		$manager = $this->newManager();
		$manager->recorder->answers = ['FROM user_tab_identity_cols' => 'ISEQ$$_7301', '.CURRVAL FROM DUAL' => '42'];
		self::assertSame('42', PradoUnit::invoke($manager, 'getLastInsertTaskUID'));
		[$identity, $current] = $manager->recorder->commands;
		self::assertSame("SELECT sequence_name FROM user_tab_identity_cols WHERE table_name=:table AND column_name='TABUID'", $identity->sql);
		self::assertSame('CRONTABS', $identity->bound[':table']);
		self::assertSame('SELECT "ISEQ$$_7301".CURRVAL FROM DUAL', $current->sql);

		$manager->recorder->answers = [];
		self::assertNull(PradoUnit::invoke($manager, 'getLastInsertTaskUID'), 'no identity sequence');
	}
}
