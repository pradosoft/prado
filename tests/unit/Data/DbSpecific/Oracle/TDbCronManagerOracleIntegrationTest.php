<?php

namespace Prado\Test\Unit\Data\DbSpecific\Oracle;

use Prado\Data\TDbConnection;
use Prado\Data\TDbDriver;
use Prado\Test\Unit\Harness\Traits\PradoUnitDataConnectionTrait;
use Prado\Test\Unit\PradoUnit;
use Prado\Test\Unit\Util\Cron\TTestCronModuleTask;
use Prado\Util\Cron\TDbCronManager;

/**
 * {@see TDbCronManager} on a live Oracle server: it creates, indexes, and migrates its table, and
 * stores, runs, logs, and removes its tasks.
 */
class TDbCronManagerOracleIntegrationTest extends \PHPUnit\Framework\TestCase
{
	use PradoUnitDataConnectionTrait;

	/** @var string[] the tables to drop after the test */
	private array $_tables = [];

	/** @var TDbCronManager[] the managers to unlisten after the test */
	private array $_managers = [];

	private ?TDbConnection $_connection = null;

	protected function setUp(): void
	{
	}

	protected function tearDown(): void
	{
		foreach ($this->_tables as $table) {
			$this->dropTable($table);
		}
		foreach ($this->_managers as $manager) {
			$manager->unlisten();
		}
		$this->_tables = [];
		$this->_managers = [];
		$this->_connection = null;
	}

	protected function getDbDriver(): ?string
	{
		return TDbDriver::DRIVER_OCI;
	}

	protected function getTestTables(): array
	{
		return [];
	}

	private function oracleConnection(): TDbConnection
	{
		if ($this->_connection === null) {
			$connection = $this->setUpConnection();
			if ($connection === null) {
				self::markTestSkipped('No Oracle connection.');
			}
			$this->_connection = $connection;
		}
		return $this->_connection;
	}

	/**
	 * Drops a table, when it exists, on any Oracle version.
	 * @param string $table the table
	 */
	private function dropTable(string $table): void
	{
		$this->oracleConnection()->createCommand(
			"BEGIN EXECUTE IMMEDIATE 'DROP TABLE {$table} PURGE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;"
		)->execute();
	}

	private function newManager(string $table, bool $drop = true): TDbCronManager
	{
		$connection = $this->oracleConnection();
		if ($drop) {
			$this->dropTable($table);
			$this->_tables[] = $table;
		}
		$manager = $this->_managers[] = new TDbCronManager();
		PradoUnit::setProp($manager, '_conn', $connection);
		$manager->setTableName($table);
		$manager->init(null);
		return $manager;
	}

	private function newTask(string $name, string $schedule = '* * * * *'): TTestCronModuleTask
	{
		$task = new TTestCronModuleTask();
		$task->setName($name);
		$task->setSchedule($schedule);
		return $task;
	}

	/**
	 * @return array<string, array{type: string, precision: ?int}> the columns of the table
	 */
	private function columns(string $table): array
	{
		$rows = $this->oracleConnection()->createCommand(
			"SELECT column_name, data_type, data_precision FROM user_tab_columns WHERE table_name='" . strtoupper($table) . "' ORDER BY column_id"
		)->queryAll();
		$columns = [];
		foreach ($rows as $row) {
			$row = array_change_key_case($row, CASE_LOWER);
			$columns[strtolower($row['column_name'])] = ['type' => $row['data_type'], 'precision' => $row['data_precision'] === null ? null : (int) $row['data_precision']];
		}
		return $columns;
	}

	public function testCreatesTheTableAndItsIndexes()
	{
		$manager = $this->newManager('cronora_create');
		self::assertSame(['created' => true, 'column' => null, 'run' => false], $manager->migrateTable());
		self::assertSame(['created' => false, 'column' => null, 'run' => false], $manager->migrateTable(), 'a second migration changes nothing');

		$columns = $this->columns('cronora_create');
		self::assertSame(array_keys(TDbCronManager::ORACLE_COLUMNS), array_keys($columns));
		self::assertSame(['type' => 'NUMBER', 'precision' => 19], $columns['nextexectime']);
		self::assertSame('CLOB', $columns['options']['type']);
		self::assertSame('VARCHAR2', $columns['name']['type']);

		$indexes = $this->oracleConnection()->createCommand(
			"SELECT index_name FROM user_indexes WHERE table_name='CRONORA_CREATE' AND index_name LIKE 'CRONORA_CREATE%' ORDER BY index_name"
		)->queryColumn();
		self::assertSame(['CRONORA_CREATE_TACTIVE', 'CRONORA_CREATE_TCLASS', 'CRONORA_CREATE_TNAME', 'CRONORA_CREATE_TNEXT', 'CRONORA_CREATE_TUSER'], $indexes);
	}

	public function testMigratesATableCreatedBefore440()
	{
		$this->dropTable('cronora_old');
		$this->_tables[] = 'cronora_old';
		$connection = $this->oracleConnection();
		$connection->createCommand('CREATE TABLE cronora_old (tabuid NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, '
			. 'name VARCHAR2(127) NOT NULL, schedule VARCHAR2(127) NOT NULL, task VARCHAR2(256) NOT NULL, moduleid VARCHAR2(127) NULL, '
			. 'username VARCHAR2(127) NULL, options CLOB NULL, processcount NUMBER(10) DEFAULT 0 NOT NULL, lastexectime VARCHAR2(20) NULL, active NUMBER(1) NULL)')->execute();
		$task = $this->newTask('oraold', '0 0 1 1 ? 2099');
		$cmd = $connection->createCommand("INSERT INTO cronora_old (name, schedule, task, options, active) VALUES ('oraold', '0 0 1 1 ? 2099', 'x', :options, 1)");
		$cmd->bindValue(':options', base64_encode(serialize($task)));
		$cmd->execute();

		$manager = $this->newManager('cronora_old', false);
		self::assertSame(['created' => false, 'column' => 1, 'run' => true], $manager->migrateTable());

		$columns = $this->columns('cronora_old');
		foreach (array_merge(['nextexectime'], array_keys(TDbCronManager::RUN_COLUMNS)) as $column) {
			self::assertArrayHasKey($column, $columns);
		}
		self::assertSame(['type' => 'NUMBER', 'precision' => 19], $columns['nextexectime']);
		$stored = (int) $connection->createCommand("SELECT nextexectime FROM cronora_old WHERE name='oraold'")->queryScalar();
		self::assertGreaterThan(2 ** 31, $stored, 'the trigger after 2038 is filled');
	}

	public function testStoresRunsLogsAndRemovesTasks()
	{
		$manager = $this->newManager('cronora_tasks');
		$task = $this->newTask('oratask');
		$task->setPropertyA("a value with a \0 NUL byte");
		self::assertTrue($manager->addTask($task));
		self::assertFalse($manager->addTask($this->newTask('oratask')), 'the name is taken');
		self::assertTrue($manager->taskExists('oratask'));
		self::assertTrue($manager->addTask($this->newTask('orafar', '0 0 1 1 ? 2099')));

		$reader = $this->newManager('cronora_tasks', false);
		$read = $reader->getTask('oratask');
		self::assertInstanceOf(TTestCronModuleTask::class, $read);
		self::assertSame("a value with a \0 NUL byte", $read->getPropertyA());
		self::assertSame(['orafar', 'oratask'], array_keys($reader->getTasks()));
		self::assertSame(['oratask'], array_keys($reader->getTasks(null, 1, 1)), 'the second page of one task');
		self::assertSame(2, $reader->getTasksCount());

		self::assertTrue($manager->runTaskNow($manager->getTask('oratask')));
		$results = $manager->getTaskResults();
		self::assertSame(TDbCronManager::RESULT_OK, $results['oratask']['result']);
		self::assertSame(1, $results['oratask']['count']);
		self::assertSame(1, $results['oratask']['ok']);

		$log = $manager->getCronLog('oratask');
		self::assertCount(1, $log);
		self::assertSame(TDbCronManager::RESULT_OK, $log[0]['lastresult'], 'the run log row has the result');
		self::assertSame(1, $manager->getCronLogCount('oratask'));

		$triggers = $manager->getNextTriggers(1);
		self::assertSame(['oratask'], array_keys($triggers));
		$far = (int) $this->oracleConnection()->createCommand("SELECT nextexectime FROM cronora_tasks WHERE name='orafar' AND active IS NOT NULL")->queryScalar();
		self::assertGreaterThan(2 ** 31, $far);

		self::assertSame(1, $manager->clearCronLog());
		self::assertTrue($manager->removeTask('oratask'));
		self::assertNull($manager->getTask('oratask'));
		self::assertFalse($manager->taskExists('oratask'));
	}
}
